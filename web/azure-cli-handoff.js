const BICEP_DELIMITER = "AZX_BICEP_EOF";

function shellQuote(value) {
  return `'${String(value).replaceAll("'", "'\"'\"'")}'`;
}

function validateResourceGroup(value) {
  if (!/^[A-Za-z0-9._()-]{1,90}$/.test(value) || value.endsWith(".")) {
    throw new Error("Resource group must be 1-90 Azure-safe characters and cannot end with a period.");
  }
}

function validateRegion(value) {
  if (!/^[A-Za-z0-9]{1,64}$/.test(value)) {
    throw new Error("Region must contain only letters and numbers.");
  }
}

export function deploymentScriptName(appName) {
  const safe = String(appName || "app")
    .toLowerCase()
    .replace(/[^a-z0-9-]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 48);
  return `deploy-${safe || "app"}.sh`;
}

export function buildAzureCliScript({ bicep, resourceGroup, region, needsPgPassword }) {
  validateResourceGroup(resourceGroup);
  validateRegion(region);
  const normalizedBicep = String(bicep || "").replace(/\r\n/g, "\n").replace(/\n?$/, "");
  if (!normalizedBicep || normalizedBicep.split("\n").includes(BICEP_DELIMITER)) {
    throw new Error("Generated Bicep cannot be embedded safely in the deployment script.");
  }

  const passwordSetup = needsPgPassword
    ? [
        'command -v python3 >/dev/null || { echo "python3 is required to prepare the secure parameter file." >&2; exit 1; }',
        'PARAMS_FILE="$WORK_DIR/params.json"',
        'read -rsp "PostgreSQL admin password: " PG_ADMIN_PASSWORD; echo',
        '[[ -n "$PG_ADMIN_PASSWORD" ]] || { echo "PostgreSQL admin password cannot be empty." >&2; exit 1; }',
        "printf '%s' \"$PG_ADMIN_PASSWORD\" | python3 -c 'import json,sys; json.dump({\"postgresAdminPassword\":{\"value\":sys.stdin.read()}}, open(sys.argv[1], \"w\"))' \"$PARAMS_FILE\"",
        "unset PG_ADMIN_PASSWORD",
        'chmod 600 "$PARAMS_FILE"',
        'PARAM_ARGS+=("@$PARAMS_FILE")',
      ]
    : [];

  return [
    "#!/usr/bin/env bash",
    "set -euo pipefail",
    "umask 077",
    "",
    "# Generated by azx. Review this file before running it.",
    `RESOURCE_GROUP=${shellQuote(resourceGroup)}`,
    `REGION=${shellQuote(region)}`,
    'DEPLOYMENT_NAME="azx-$(date -u +%Y%m%d%H%M%S)"',
    'WORK_DIR="$(mktemp -d)"',
    "trap 'rm -rf \"$WORK_DIR\"' EXIT",
    'BICEP_FILE="$WORK_DIR/main.bicep"',
    "",
    `cat >"$BICEP_FILE" <<'${BICEP_DELIMITER}'`,
    normalizedBicep,
    BICEP_DELIMITER,
    "",
    'command -v az >/dev/null || { echo "Azure CLI is required." >&2; exit 1; }',
    'if [[ -n "${AZURE_SUBSCRIPTION_ID:-}" ]]; then',
    '  az account set --subscription "$AZURE_SUBSCRIPTION_ID"',
    "fi",
    'az account show --query "{subscription:name, subscriptionId:id, tenantId:tenantId}" -o table',
    "",
    'echo "Ensuring prerequisite resource group $RESOURCE_GROUP in $REGION..."',
    'GROUP_EXISTS="$(az group exists --name "$RESOURCE_GROUP" -o tsv)"',
    'if [[ "$GROUP_EXISTS" != "true" ]]; then',
    '  az group create --name "$RESOURCE_GROUP" --location "$REGION" --only-show-errors -o none',
    "fi",
    'PARAM_ARGS=("location=$REGION")',
    ...passwordSetup,
    "",
    'echo "Running ARM what-if; no application resources are changed by this step..."',
    'az deployment group what-if --resource-group "$RESOURCE_GROUP" \\',
    '  --name "$DEPLOYMENT_NAME" --template-file "$BICEP_FILE" \\',
    '  --parameters "${PARAM_ARGS[@]}"',
    "",
    'read -rp "Review the what-if above. Type deploy to create these resources: " AZX_CONFIRM',
    '[[ "$AZX_CONFIRM" == "deploy" ]] || { echo "Canceled; application resources were not deployed."; exit 0; }',
    "",
    'az deployment group create --resource-group "$RESOURCE_GROUP" \\',
    '  --name "$DEPLOYMENT_NAME" --template-file "$BICEP_FILE" \\',
    '  --parameters "${PARAM_ARGS[@]}" --only-show-errors -o json',
    "",
    'echo "Infrastructure deployment complete. Compute still uses placeholder images; application code was not deployed."',
    "",
  ].join("\n");
}
